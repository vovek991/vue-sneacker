-- ========== diplom.sql ==========
-- Создание базы данных и выбор её
CREATE DATABASE IF NOT EXISTS diplom;
USE diplom;

-- ========== Структура таблиц ==========

-- Таблица пользователей
CREATE TABLE IF NOT EXISTS пользователи (
  id_пользователя INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  пароль VARCHAR(255) NOT NULL,
  имя VARCHAR(100) NOT NULL,
  фамилия VARCHAR(100) NOT NULL,
  телефон VARCHAR(20),
  дата_регистрации DATETIME NOT NULL,
  дата_последнего_входа DATETIME,
  является_админом BOOLEAN DEFAULT FALSE
);

-- Таблица брендов
CREATE TABLE IF NOT EXISTS бренды (
  id_бренда INT AUTO_INCREMENT PRIMARY KEY,
  название VARCHAR(100) NOT NULL UNIQUE,
  описание TEXT,
  url_логотипа VARCHAR(255)
);

-- Таблица категорий
CREATE TABLE IF NOT EXISTS категории (
  id_категории INT AUTO_INCREMENT PRIMARY KEY,
  название VARCHAR(100) NOT NULL UNIQUE,
  описание TEXT
);

-- Таблица заказов
CREATE TABLE IF NOT EXISTS заказы (
  id_заказа INT AUTO_INCREMENT PRIMARY KEY,
  id_пользователя INT NOT NULL,
  сумма_заказа DECIMAL(10,2) NOT NULL,
  статус VARCHAR(50) NOT NULL,
  дата_заказа DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  адрес_доставки TEXT NOT NULL,
  контактный_телефон VARCHAR(20) NOT NULL,
  FOREIGN KEY (id_пользователя) REFERENCES пользователи(id_пользователя)
);

-- Таблица товаров заказа
CREATE TABLE IF NOT EXISTS товары_заказа (
  id INT AUTO_INCREMENT PRIMARY KEY,
  id_заказа INT NOT NULL,
  id_кроссовок INT NOT NULL,
  id_размера INT NOT NULL,
  количество INT NOT NULL DEFAULT 1,
  цена DECIMAL(10,2) NOT NULL,
  FOREIGN KEY (id_заказа) REFERENCES заказы(id_заказа),
  FOREIGN KEY (id_кроссовок) REFERENCES кроссовки(id_кроссовок),
  FOREIGN KEY (id_размера) REFERENCES размеры_наличие(id_размера)
);

-- Таблица корзины
CREATE TABLE IF NOT EXISTS корзина (
  id INT AUTO_INCREMENT PRIMARY KEY,
  id_пользователя INT NOT NULL,
  id_кроссовок INT NOT NULL,
  id_размера INT NOT NULL,
  количество INT NOT NULL DEFAULT 1,
  FOREIGN KEY (id_пользователя) REFERENCES пользователи(id_пользователя),
  FOREIGN KEY (id_кроссовок) REFERENCES кроссовки(id_кроссовок),
  FOREIGN KEY (id_размера) REFERENCES размеры_наличие(id_размера)
);

-- Таблица данных оплаты
CREATE TABLE IF NOT EXISTS данные_оплаты (
  id INT AUTO_INCREMENT PRIMARY KEY,
  id_заказа INT NOT NULL,
  номер_карты VARCHAR(16) NOT NULL,
  срок_действия VARCHAR(5) NOT NULL,
  имя_владельца VARCHAR(100) NOT NULL,
  сохранить_карту BOOLEAN DEFAULT FALSE,
  FOREIGN KEY (id_заказа) REFERENCES заказы(id_заказа)
);

-- Таблица избранного
CREATE TABLE IF NOT EXISTS избранное (
  id_избранного INT AUTO_INCREMENT PRIMARY KEY,
  id_пользователя INT NOT NULL,
  id_кроссовок INT NOT NULL,
  дата_добавления TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (id_пользователя) REFERENCES пользователи(id_пользователя),
  FOREIGN KEY (id_кроссовок) REFERENCES кроссовки(id_кроссовок)
);

-- Таблица изображений кроссовок
CREATE TABLE IF NOT EXISTS изображения_кроссовок (
  id_изображения INT AUTO_INCREMENT PRIMARY KEY,
  id_кроссовок INT NOT NULL,
  url_изображения VARCHAR(255) NOT NULL,
  основное TINYINT(1) DEFAULT 0,
  FOREIGN KEY (id_кроссовок) REFERENCES кроссовки(id_кроссовок)
);

-- Таблица ролей
CREATE TABLE IF NOT EXISTS роли (
  id_роли INT AUTO_INCREMENT PRIMARY KEY,
  название_роли VARCHAR(50) NOT NULL,
  описание TEXT
);

-- Таблица ролей пользователей
CREATE TABLE IF NOT EXISTS роли_пользователей (
  id_пользователя INT NOT NULL,
  id_роли INT NOT NULL,
  FOREIGN KEY (id_пользователя) REFERENCES пользователи(id_пользователя),
  FOREIGN KEY (id_роли) REFERENCES роли(id_роли)
);

-- Таблица сообщений чата
CREATE TABLE IF NOT EXISTS сообщения_чата (
  id_сообщения INT AUTO_INCREMENT PRIMARY KEY,
  id_пользователя INT DEFAULT NULL,
  текст_сообщения TEXT NOT NULL,
  от_пользователя TINYINT(1) NOT NULL,
  дата_отправки TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (id_пользователя) REFERENCES пользователи(id_пользователя)
);

